    private void AddUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddUserActionPerformed
        try {
        if (UserName.getText().isEmpty() || Password.getPassword().length == 0) {
            JOptionPane.showMessageDialog(this, "Please fill all required fields (Id, Name, Password)!");
            return;
        }
        if (Team.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Please select a Team first!");
            return;
        }
    int id = Integer.parseInt(Id.getText());
    String name = UserName.getText();
    String email = gmail.getText();
    String password = new String(Password.getPassword());
    String confirm = new String(ConfirmPassword.getPassword());
    String job = JopField.getText();
    UserRole role = UserRole.valueOf(Role.getSelectedItem().toString().toUpperCase());
    boolean Status = status.isSelected();
    String team = Team.getSelectedItem().toString();
    int age = 0;
    try {
        age = Integer.parseInt(Age.getText());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Age must be a valid number!");
        return;
    }
    
     UserClass newUser = new UserClass(id,name,email,password,confirm,job,role,Status,team,age);
     DataStore.usersList.add(newUser);
     JOptionPane.showMessageDialog(this, "User Added Successfully!");
     searchActionPerformed(null);  
     clearFields();
     setInterfaceState("VIEW");
        }
        catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "ID must be a number!");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_AddUserActionPerformed

