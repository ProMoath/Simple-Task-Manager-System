    private void deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteActionPerformed
        int selectedRow = showuser.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Select a user to delete!");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this, "Are you sure?");
    if (confirm == JOptionPane.YES_OPTION) {
        
        int idToDelete = Integer.parseInt(showuser.getValueAt(selectedRow, 0).toString());
        
        
        for (int i = 0; i < DataStore.usersList.size(); i++) {
            if (DataStore.usersList.get(i).getId() == idToDelete) {
                DataStore.usersList.remove(i);
                break;
            }
        }
        
        
        searchActionPerformed(null);
        JOptionPane.showMessageDialog(this, "User Deleted.");
    }
        
    }//GEN-LAST:event_deleteActionPerformed
