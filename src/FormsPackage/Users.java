    private void UpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateActionPerformed
    if (Id.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please select a user to update first!");
        return;
    }

    int targetId = Integer.parseInt(Id.getText());
    int foundIndex = -1;
    UserClass oldUser = null;
    for (int i = 0; i < DataStore.usersList.size(); i++) {
        if (DataStore.usersList.get(i).getId() == targetId) {
            foundIndex = i;
            oldUser = DataStore.usersList.get(i);
            break;
        }
    }

    if (foundIndex != -1 && oldUser != null) {
        String name = UserName.getText();
        String email = gmail.getText();
        String job = JopField.getText();
        UserRole role = UserRole.valueOf(Role.getSelectedItem().toString().toUpperCase()); 
        
        boolean isStatus = status.isSelected();
        String team = Team.getSelectedItem().toString();
        int age = 0;
        try {
            age = Integer.parseInt(Age.getText());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Age must be a valid number!");
            return;
        }
        
        String oldPass = oldUser.getPass();
        UserClass updatedUser = new UserClass(
            targetId, 
            name, 
            email, 
            oldPass,
            oldPass,
            job, 
            role, 
            isStatus, 
            team,
            age
        );

        
        DataStore.usersList.set(foundIndex, updatedUser);

        JOptionPane.showMessageDialog(this, "User updated successfully!");
        searchActionPerformed(null); 
        clearFields();
        setInterfaceState("VIEW");
        
    } else 
        JOptionPane.showMessageDialog(this, "Error: User not found!");
    
    }//GEN-LAST:event_UpdateActionPerformed

